-- ============================================================================
-- NOVURA MARKETPLACE - DATABASE SCHEMA (PostgreSQL / Supabase)
-- Path: database/schema.sql
--
-- Run in Supabase: SQL Editor > New query > paste this whole file > Run.
-- Safe to run more than once (IF NOT EXISTS everywhere).
--
-- Conventions
--   * Flags are SMALLINT 0/1 (not boolean) so the PHP code can keep using "= 1".
--   * "ENUM" columns are VARCHAR + CHECK constraints.
--   * updated_at is maintained by a trigger (PostgreSQL has no ON UPDATE).
--   * Row Level Security is ENABLED on every table with NO policies, so
--     Supabase's public REST API cannot read or write anything.
--     The PHP app connects as the database owner, which bypasses RLS.
-- Tables (14): users, vendors, categories, products, product_images,
--              product_variants, carts, cart_items, orders, order_items,
--              payments, reviews, wishlists, banners
-- ============================================================================

SET TIME ZONE 'Africa/Lagos';

-- Keeps updated_at current on every UPDATE
CREATE OR REPLACE FUNCTION novura_set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ----------------------------------------------------------------------------
-- 1. USERS (buyers, vendors, admins share one login table)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role                   VARCHAR(10)  NOT NULL DEFAULT 'buyer',
    first_name             VARCHAR(80)  NOT NULL,
    last_name              VARCHAR(80)  NOT NULL,
    email                  VARCHAR(190) NOT NULL,
    phone                  VARCHAR(30),
    password_hash          VARCHAR(255) NOT NULL,
    avatar                 VARCHAR(255),
    address                VARCHAR(255),
    city                   VARCHAR(100),
    state                  VARCHAR(100),
    status                 VARCHAR(10)  NOT NULL DEFAULT 'active',
    email_verified_at      TIMESTAMP,
    reset_token_hash       VARCHAR(255),
    reset_token_expires_at TIMESTAMP,
    last_login_at          TIMESTAMP,
    created_at             TIMESTAMP    NOT NULL DEFAULT NOW(),
    updated_at             TIMESTAMP    NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT chk_users_role   CHECK (role IN ('buyer','vendor','admin')),
    CONSTRAINT chk_users_status CHECK (status IN ('active','suspended'))
);
CREATE INDEX IF NOT EXISTS idx_users_role_status ON users (role, status);

-- ----------------------------------------------------------------------------
-- 2. VENDORS (one store per vendor user)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS vendors (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         INTEGER      NOT NULL,
    store_name      VARCHAR(150) NOT NULL,
    slug            VARCHAR(170) NOT NULL,
    description     TEXT,
    logo            VARCHAR(255),
    banner          VARCHAR(255),
    phone           VARCHAR(30),
    address         VARCHAR(255),
    city            VARCHAR(100),
    state           VARCHAR(100),
    commission_rate NUMERIC(5,2) NOT NULL DEFAULT 10.00,
    bank_name       VARCHAR(100),
    account_name    VARCHAR(150),
    account_number  VARCHAR(20),
    status          VARCHAR(10)  NOT NULL DEFAULT 'pending',
    created_at      TIMESTAMP    NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMP    NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_vendors_user UNIQUE (user_id),
    CONSTRAINT uq_vendors_slug UNIQUE (slug),
    CONSTRAINT fk_vendors_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT chk_vendors_status CHECK (status IN ('pending','approved','suspended','rejected')),
    CONSTRAINT chk_vendors_commission CHECK (commission_rate >= 0 AND commission_rate <= 100)
);
CREATE INDEX IF NOT EXISTS idx_vendors_status ON vendors (status);

-- ----------------------------------------------------------------------------
-- 3. CATEGORIES (self-referencing: parent -> sub-category)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS categories (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id  INTEGER,
    name       VARCHAR(120) NOT NULL,
    slug       VARCHAR(140) NOT NULL,
    icon       VARCHAR(80),
    image      VARCHAR(255),
    sort_order INTEGER      NOT NULL DEFAULT 0,
    is_active  SMALLINT     NOT NULL DEFAULT 1,
    created_at TIMESTAMP    NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_categories_slug UNIQUE (slug),
    CONSTRAINT fk_categories_parent FOREIGN KEY (parent_id) REFERENCES categories (id) ON DELETE SET NULL,
    CONSTRAINT chk_categories_active CHECK (is_active IN (0,1))
);
CREATE INDEX IF NOT EXISTS idx_categories_parent ON categories (parent_id, sort_order);

-- ----------------------------------------------------------------------------
-- 4. PRODUCTS
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS products (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_id          INTEGER       NOT NULL,
    category_id        INTEGER       NOT NULL,
    name               VARCHAR(200)  NOT NULL,
    slug               VARCHAR(230)  NOT NULL,
    sku                VARCHAR(60),
    brand              VARCHAR(100),
    short_description  VARCHAR(500),
    description        TEXT,
    price              NUMERIC(12,2) NOT NULL,
    compare_price      NUMERIC(12,2),
    stock_quantity     INTEGER       NOT NULL DEFAULT 0,
    is_featured        SMALLINT      NOT NULL DEFAULT 0,
    is_flash_sale      SMALLINT      NOT NULL DEFAULT 0,
    flash_sale_price   NUMERIC(12,2),
    flash_sale_ends_at TIMESTAMP,
    avg_rating         NUMERIC(3,2)  NOT NULL DEFAULT 0.00,
    review_count       INTEGER       NOT NULL DEFAULT 0,
    view_count         INTEGER       NOT NULL DEFAULT 0,
    status             VARCHAR(10)   NOT NULL DEFAULT 'pending',
    created_at         TIMESTAMP     NOT NULL DEFAULT NOW(),
    updated_at         TIMESTAMP     NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_products_slug UNIQUE (slug),
    CONSTRAINT fk_products_vendor   FOREIGN KEY (vendor_id)   REFERENCES vendors (id)    ON DELETE CASCADE,
    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id) ON DELETE RESTRICT,
    CONSTRAINT chk_products_price  CHECK (price >= 0),
    CONSTRAINT chk_products_stock  CHECK (stock_quantity >= 0),
    CONSTRAINT chk_products_flags  CHECK (is_featured IN (0,1) AND is_flash_sale IN (0,1)),
    CONSTRAINT chk_products_status CHECK (status IN ('draft','pending','active','rejected','archived'))
);
CREATE INDEX IF NOT EXISTS idx_products_vendor   ON products (vendor_id, status);
CREATE INDEX IF NOT EXISTS idx_products_category ON products (category_id, status);
CREATE INDEX IF NOT EXISTS idx_products_flash    ON products (is_flash_sale, flash_sale_ends_at);
CREATE INDEX IF NOT EXISTS idx_products_featured ON products (is_featured, status);
CREATE INDEX IF NOT EXISTS idx_products_price    ON products (price);

-- ----------------------------------------------------------------------------
-- 5. PRODUCT IMAGES
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS product_images (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER      NOT NULL,
    image_path VARCHAR(255) NOT NULL,
    is_primary SMALLINT     NOT NULL DEFAULT 0,
    sort_order INTEGER      NOT NULL DEFAULT 0,
    created_at TIMESTAMP    NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_product_images_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT chk_product_images_primary CHECK (is_primary IN (0,1))
);
CREATE INDEX IF NOT EXISTS idx_product_images_product ON product_images (product_id, is_primary, sort_order);

-- ----------------------------------------------------------------------------
-- 6. PRODUCT VARIANTS (e.g. Size: XL, Colour: Black)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS product_variants (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id       INTEGER       NOT NULL,
    attribute_name   VARCHAR(60)   NOT NULL,
    attribute_value  VARCHAR(100)  NOT NULL,
    sku              VARCHAR(60),
    price_adjustment NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    stock_quantity   INTEGER       NOT NULL DEFAULT 0,
    is_active        SMALLINT      NOT NULL DEFAULT 1,
    CONSTRAINT fk_variants_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT chk_variants_stock  CHECK (stock_quantity >= 0),
    CONSTRAINT chk_variants_active CHECK (is_active IN (0,1))
);
CREATE INDEX IF NOT EXISTS idx_variants_product ON product_variants (product_id, is_active);

-- ----------------------------------------------------------------------------
-- 7. CARTS (logged-in user OR guest session)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS carts (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INTEGER,
    session_id VARCHAR(128),
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_carts_user    UNIQUE (user_id),
    CONSTRAINT uq_carts_session UNIQUE (session_id),
    CONSTRAINT fk_carts_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT chk_carts_owner CHECK (user_id IS NOT NULL OR session_id IS NOT NULL)
);

-- ----------------------------------------------------------------------------
-- 8. CART ITEMS (price is read live from products; never stored here)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS cart_items (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id    INTEGER   NOT NULL,
    product_id INTEGER   NOT NULL,
    variant_id INTEGER,
    quantity   INTEGER   NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_cart_items_cart    FOREIGN KEY (cart_id)    REFERENCES carts (id)            ON DELETE CASCADE,
    CONSTRAINT fk_cart_items_product FOREIGN KEY (product_id) REFERENCES products (id)         ON DELETE CASCADE,
    CONSTRAINT fk_cart_items_variant FOREIGN KEY (variant_id) REFERENCES product_variants (id) ON DELETE CASCADE,
    CONSTRAINT chk_cart_items_qty CHECK (quantity > 0)
);
CREATE INDEX IF NOT EXISTS idx_cart_items_lookup ON cart_items (cart_id, product_id, variant_id);

-- ----------------------------------------------------------------------------
-- 9. ORDERS (shipping details are snapshotted at purchase time)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS orders (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number     VARCHAR(30)   NOT NULL,
    user_id          INTEGER       NOT NULL,
    status           VARCHAR(12)   NOT NULL DEFAULT 'pending',
    payment_method   VARCHAR(10)   NOT NULL,
    payment_status   VARCHAR(10)   NOT NULL DEFAULT 'unpaid',
    subtotal         NUMERIC(12,2) NOT NULL,
    shipping_fee     NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    discount         NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    total            NUMERIC(12,2) NOT NULL,
    currency         CHAR(3)       NOT NULL DEFAULT 'NGN',
    shipping_name    VARCHAR(160)  NOT NULL,
    shipping_phone   VARCHAR(30)   NOT NULL,
    shipping_address VARCHAR(255)  NOT NULL,
    shipping_city    VARCHAR(100)  NOT NULL,
    shipping_state   VARCHAR(100)  NOT NULL,
    notes            VARCHAR(500),
    created_at       TIMESTAMP     NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMP     NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_orders_number UNIQUE (order_number),
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_orders_total  CHECK (total >= 0),
    CONSTRAINT chk_orders_status CHECK (status IN ('pending','paid','processing','shipped','delivered','cancelled','refunded')),
    CONSTRAINT chk_orders_method CHECK (payment_method IN ('paystack','cod')),
    CONSTRAINT chk_orders_pay_status CHECK (payment_status IN ('unpaid','paid','failed','refunded'))
);
CREATE INDEX IF NOT EXISTS idx_orders_user   ON orders (user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_orders_status ON orders (status, payment_status);

-- ----------------------------------------------------------------------------
-- 10. ORDER ITEMS (per-vendor fulfilment + commission split)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS order_items (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id          INTEGER       NOT NULL,
    product_id        INTEGER,
    variant_id        INTEGER,
    vendor_id         INTEGER       NOT NULL,
    product_name      VARCHAR(200)  NOT NULL,
    variant_label     VARCHAR(160),
    unit_price        NUMERIC(12,2) NOT NULL,
    quantity          INTEGER       NOT NULL,
    line_total        NUMERIC(12,2) NOT NULL,
    commission_amount NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    vendor_earning    NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    status            VARCHAR(12)   NOT NULL DEFAULT 'pending',
    tracking_note     VARCHAR(255),
    created_at        TIMESTAMP     NOT NULL DEFAULT NOW(),
    updated_at        TIMESTAMP     NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_order_items_order   FOREIGN KEY (order_id)   REFERENCES orders (id)           ON DELETE CASCADE,
    CONSTRAINT fk_order_items_product FOREIGN KEY (product_id) REFERENCES products (id)         ON DELETE SET NULL,
    CONSTRAINT fk_order_items_variant FOREIGN KEY (variant_id) REFERENCES product_variants (id) ON DELETE SET NULL,
    CONSTRAINT fk_order_items_vendor  FOREIGN KEY (vendor_id)  REFERENCES vendors (id)          ON DELETE RESTRICT,
    CONSTRAINT chk_order_items_qty    CHECK (quantity > 0),
    CONSTRAINT chk_order_items_status CHECK (status IN ('pending','processing','shipped','delivered','cancelled'))
);
CREATE INDEX IF NOT EXISTS idx_order_items_order   ON order_items (order_id);
CREATE INDEX IF NOT EXISTS idx_order_items_vendor  ON order_items (vendor_id, status);
CREATE INDEX IF NOT EXISTS idx_order_items_product ON order_items (product_id);

-- ----------------------------------------------------------------------------
-- 11. PAYMENTS
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS payments (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         INTEGER       NOT NULL,
    provider         VARCHAR(10)   NOT NULL,
    reference        VARCHAR(100)  NOT NULL,
    amount           NUMERIC(12,2) NOT NULL,
    currency         CHAR(3)       NOT NULL DEFAULT 'NGN',
    status           VARCHAR(10)   NOT NULL DEFAULT 'pending',
    gateway_response TEXT,
    paid_at          TIMESTAMP,
    created_at       TIMESTAMP     NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMP     NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_payments_reference UNIQUE (reference),
    CONSTRAINT fk_payments_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT,
    CONSTRAINT chk_payments_provider CHECK (provider IN ('paystack','cod')),
    CONSTRAINT chk_payments_status   CHECK (status IN ('pending','success','failed','refunded'))
);
CREATE INDEX IF NOT EXISTS idx_payments_order  ON payments (order_id);
CREATE INDEX IF NOT EXISTS idx_payments_status ON payments (status);

-- ----------------------------------------------------------------------------
-- 12. REVIEWS (one review per buyer per product)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS reviews (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    INTEGER      NOT NULL,
    user_id       INTEGER      NOT NULL,
    order_item_id INTEGER,
    rating        SMALLINT     NOT NULL,
    title         VARCHAR(150),
    comment       TEXT,
    status        VARCHAR(10)  NOT NULL DEFAULT 'pending',
    created_at    TIMESTAMP    NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_reviews_user_product UNIQUE (user_id, product_id),
    CONSTRAINT fk_reviews_product    FOREIGN KEY (product_id)    REFERENCES products (id)    ON DELETE CASCADE,
    CONSTRAINT fk_reviews_user       FOREIGN KEY (user_id)       REFERENCES users (id)       ON DELETE CASCADE,
    CONSTRAINT fk_reviews_order_item FOREIGN KEY (order_item_id) REFERENCES order_items (id) ON DELETE SET NULL,
    CONSTRAINT chk_reviews_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT chk_reviews_status CHECK (status IN ('pending','approved','rejected'))
);
CREATE INDEX IF NOT EXISTS idx_reviews_product ON reviews (product_id, status);

-- ----------------------------------------------------------------------------
-- 13. WISHLISTS
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS wishlists (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INTEGER   NOT NULL,
    product_id INTEGER   NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_wishlists_user_product UNIQUE (user_id, product_id),
    CONSTRAINT fk_wishlists_user    FOREIGN KEY (user_id)    REFERENCES users (id)    ON DELETE CASCADE,
    CONSTRAINT fk_wishlists_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 14. BANNERS (home page sliders and promos)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS banners (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      VARCHAR(150) NOT NULL,
    subtitle   VARCHAR(255),
    image      VARCHAR(255) NOT NULL,
    link_url   VARCHAR(255),
    position   VARCHAR(10)  NOT NULL DEFAULT 'hero',
    sort_order INTEGER      NOT NULL DEFAULT 0,
    is_active  SMALLINT     NOT NULL DEFAULT 1,
    starts_at  TIMESTAMP,
    ends_at    TIMESTAMP,
    created_at TIMESTAMP    NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_banners_position CHECK (position IN ('hero','promo','sidebar')),
    CONSTRAINT chk_banners_active   CHECK (is_active IN (0,1))
);
CREATE INDEX IF NOT EXISTS idx_banners_display ON banners (position, is_active, sort_order);

-- ----------------------------------------------------------------------------
-- updated_at triggers
-- ----------------------------------------------------------------------------
DO $$
DECLARE
    t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY['users','vendors','products','carts','orders','order_items','payments'] LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS trg_%1$s_updated ON %1$I', t);
        EXECUTE format('CREATE TRIGGER trg_%1$s_updated BEFORE UPDATE ON %1$I FOR EACH ROW EXECUTE FUNCTION novura_set_updated_at()', t);
    END LOOP;
END
$$;

-- ----------------------------------------------------------------------------
-- SECURITY: lock the tables away from Supabase's public API
-- RLS on + no policies = the anon / authenticated API roles can do nothing.
-- ----------------------------------------------------------------------------
ALTER TABLE users            ENABLE ROW LEVEL SECURITY;
ALTER TABLE vendors          ENABLE ROW LEVEL SECURITY;
ALTER TABLE categories       ENABLE ROW LEVEL SECURITY;
ALTER TABLE products         ENABLE ROW LEVEL SECURITY;
ALTER TABLE product_images   ENABLE ROW LEVEL SECURITY;
ALTER TABLE product_variants ENABLE ROW LEVEL SECURITY;
ALTER TABLE carts            ENABLE ROW LEVEL SECURITY;
ALTER TABLE cart_items       ENABLE ROW LEVEL SECURITY;
ALTER TABLE orders           ENABLE ROW LEVEL SECURITY;
ALTER TABLE order_items      ENABLE ROW LEVEL SECURITY;
ALTER TABLE payments         ENABLE ROW LEVEL SECURITY;
ALTER TABLE reviews          ENABLE ROW LEVEL SECURITY;
ALTER TABLE wishlists        ENABLE ROW LEVEL SECURITY;
ALTER TABLE banners          ENABLE ROW LEVEL SECURITY;

-- Defence in depth: also remove table privileges from the API roles (Supabase only).
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON ALL TABLES    IN SCHEMA public FROM anon;
        REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        REVOKE ALL ON ALL TABLES    IN SCHEMA public FROM authenticated;
        REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM authenticated;
    END IF;
END
$$;
